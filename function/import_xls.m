function data = import_xls(workbookFile, sheetName, dataLines)
%IMPORTFILE Import data from a spreadsheet
%  DATA = IMPORTFILE(FILE) reads data from the first worksheet in the
%  Microsoft Excel spreadsheet file named FILE.  Returns the data as a
%  table.
%
%  DATA = IMPORTFILE(FILE, SHEET) reads from the specified worksheet.
%
%  DATA = IMPORTFILE(FILE, SHEET, DATALINES) reads from the specified
%  worksheet for the specified row interval(s). Specify DATALINES as a
%  positive scalar integer or a N-by-2 array of positive scalar integers
%  for dis-contiguous row intervals.
%
%  Example:
%  data = importfile("C:\Users\t243f765\Desktop\data_GSR\2025-08-25 CS02\2025-08-25_001_GSR_ledalab_era.xls", "CDA", [2, Inf]);
%
%  See also READTABLE.
%
% Auto-generated by MATLAB on 17-Nov-2025 12:50:16

%% Input handling

% If no sheet is specified, read from CDA
if nargin == 1 || isempty(sheetName)
    sheetName = "CDA";
end

% If row start and end points are not specified, define defaults
lastRowOfDataIdx = 0;
if nargin <= 2
    dataLines = [2, Inf];
    lastRowOfDataIdx = 1;
elseif dataLines(end,2) >= Inf
    lastRowOfDataIdx = size(dataLines, 1);
end

%% Set up the Import Options and import the data
opts = spreadsheetImportOptions("NumVariables", 15);

% Specify sheet and range
opts.Sheet = sheetName;
if lastRowOfDataIdx == 1
    opts.DataRange = "A" + dataLines(1, 1);
else
    opts.DataRange = "A" + dataLines(1, 1) + ":O" + dataLines(1, 2);
end

% Specify column names and types
opts.VariableNames = ["Event_Nr", "Event_NID", "Event_Name", "CDA_nSCR", "CDA_Latency_s_", "CDA_AmpSum_muS_", "CDA_SCR_muS_", "CDA_ISCR_muSxs_", "CDA_PhasicMax_muS_", "CDA_Tonic_muS_", "TTP_nSCR", "TTP_Latency_s_", "TTP_AmpSum_muS_", "Global_Mean_muS_", "Global_MaxDeflection_muS_"];
opts.VariableTypes = ["double", "double", "categorical", "double", "double", "double", "double", "double", "double", "double", "double", "double", "double", "double", "double"];

% Specify variable properties
opts = setvaropts(opts, "Event_Name", "EmptyFieldRule", "auto");

% Import the data
data = readtable(workbookFile, opts, "UseExcel", false);

for idx = 2:size(dataLines, 1)
    if idx == lastRowOfDataIdx
        opts.DataRange = "A" + dataLines(idx, 1);
    else
        opts.DataRange = "A" + dataLines(idx, 1) + ":O" + dataLines(idx, 2);
    end
    tb = readtable(workbookFile, opts, "UseExcel", false);
    data = [data; tb]; %#ok<AGROW>
end

end